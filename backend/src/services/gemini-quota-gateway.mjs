import http from 'node:http';
import {readFile} from 'node:fs/promises';
import Redis from 'ioredis';
import {config} from '../config.js';
import {query,pool} from '../db.js';
import {decryptSecret} from './secret-box.js';
import {createGateway} from './gateway-handler.mjs';
import {recordReservation,recordEvent,restoreLedger} from './gateway-ledger.mjs';
const matrix=JSON.parse(await readFile(process.env.COMPANY_MATRIX_AI_KEY_FILE,'utf8'));
const settings=(await query('SELECT gemini_key FROM saas.video_factory_settings WHERE id=true')).rows[0];
const allowedKeys=[matrix.apiKey,settings?.gemini_key?decryptSecret(settings.gemini_key):null].filter(Boolean);
const redis=new Redis(config.redisUrl,{maxRetriesPerRequest:1,commandTimeout:5000,connectTimeout:5000});
let ready=false;
redis.on('close',()=>{ready=false;});
redis.on('ready',async()=>{ready=false;try{await restoreLedger(redis);ready=true;}catch(e){console.error('[GeminiQuota] Ledger restoration failed',e.code??e.name);process.exit(1);}});
redis.on('error',()=>console.error('[GeminiQuota] Redis unavailable'));
const server=http.createServer(createGateway({redis,allowedKeys,isReady:()=>ready,recordReservation,recordEvent}));
server.requestTimeout=180000;server.headersTimeout=30000;
server.listen(4012,'127.0.0.1',()=>console.log('[GeminiQuota] Listening on 127.0.0.1:4012'));
for(const signal of ['SIGINT','SIGTERM'])process.on(signal,()=>{server.close(async()=>{redis.disconnect();await pool.end();process.exit(0);});setTimeout(()=>process.exit(1),20000).unref();});
